"""
FASE 23 — Tests de branding/contraste (3 paletas distintas).

Valida que para colores fuertes (azul saturado, rosa pastel claro, azul marino
oscuro) el algoritmo siempre encuentre un color de texto (blanco o negro) con
contraste >= 4.5 (WCAG AA) y la función extract_palette funcione con imágenes
reales creadas con Pillow.
"""
from __future__ import annotations

import io

from PIL import Image, ImageDraw

from app.core.branding import (
    accessible_palette,
    autogenerated_brand,
    contrast_ratio,
    extract_palette,
    hex_to_rgb,
    pick_text_color,
    relative_luminance,
    rgb_to_hex,
)


# ── Helpers ───────────────────────────────────────────────────────────────────

def _make_solid_png(width: int, height: int, fill: str, path: str | None = None) -> bytes:
    img = Image.new("RGB", (width, height), fill)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def _make_split_png(top_fill: str, bottom_fill: str, size: int = 100) -> bytes:
    img = Image.new("RGB", (size, size))
    draw = ImageDraw.Draw(img)
    draw.rectangle([0, 0, size, size // 2], fill=top_fill)
    draw.rectangle([0, size // 2, size, size], fill=bottom_fill)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


# ── Conversión HEX ↔ RGB ──────────────────────────────────────────────────────

def test_hex_to_rgb_valid():
    assert hex_to_rgb("#000000") == (0, 0, 0)
    assert hex_to_rgb("FFFFFF") == (255, 255, 255)
    assert hex_to_rgb("#3E63DD") == (62, 99, 221)
    assert hex_to_rgb("  #AbC123  ") == (171, 193, 35)


def test_hex_to_rgb_invalid():
    import pytest
    for bad in [None, "", "#FFF", "#12345", "#GGGGGG", 123]:
        try:
            hex_to_rgb(bad)  # type: ignore
        except (ValueError, TypeError):
            continue
        else:
            raise AssertionError(f"Debería rechazar {bad!r}")


def test_rgb_to_hex_normalizes():
    assert rgb_to_hex((-10, 300, 0)) == "#00FF00"


# ── Contraste ─────────────────────────────────────────────────────────────────

def test_relative_luminance_black_is_zero():
    assert abs(relative_luminance((0, 0, 0))) < 0.001


def test_relative_luminance_white_is_one():
    assert abs(relative_luminance((255, 255, 255)) - 1.0) < 0.001


def test_contrast_ratio_self_is_1():
    c = contrast_ratio((128, 128, 128), (128, 128, 128))
    assert abs(c - 1.0) < 0.01


def test_contrast_ratio_white_vs_black_is_max():
    c = contrast_ratio((255, 255, 255), (0, 0, 0))
    assert c > 20.0


# ── pick_text_color ───────────────────────────────────────────────────────────

def test_pick_text_white_on_dark():
    color, ratio = pick_text_color((20, 20, 20))
    assert color.upper() == "#FFFFFF"
    assert ratio >= 4.5


def test_pick_text_black_on_light():
    color, ratio = pick_text_color((240, 240, 240))
    assert color.upper() in ("#0A0A0B", "#000000")
    assert ratio >= 4.5


def test_pick_text_saturated_red_selects_readable():
    """#FF0000 con blanco da ratio < 4.5, con negro da > 4.5 → debe elegir negro."""
    color, ratio = pick_text_color((255, 0, 0))
    assert ratio >= 4.5


# ── 3 paletas: saturado, pastel, oscuro ───────────────────────────────────────

PALETTES = {
    "saturado": {"primary": "#FF3333", "secondary": "#1A1A2E"},
    "pastel":   {"primary": "#FFB3C1", "secondary": "#FFFFFF"},
    "oscuro":   {"primary": "#14213D", "secondary": "#FCA311"},
}


def test_accessible_palette_saturated():
    info = accessible_palette(PALETTES["saturado"]["primary"])
    assert info["is_valid"] is True
    assert info["level"] in ("AA", "AAA")


def test_accessible_palette_pastel():
    info = accessible_palette(PALETTES["pastel"]["primary"], PALETTES["pastel"]["secondary"])
    assert info["is_valid"] is True
    assert info["level"] in ("AA", "AAA")


def test_accessible_palette_dark():
    info = accessible_palette(PALETTES["oscuro"]["primary"], PALETTES["oscuro"]["secondary"])
    assert info["is_valid"] is True
    assert info["level"] in ("AA", "AAA")


# ── Extracción desde imagen real ──────────────────────────────────────────────

def test_extract_palette_from_solid_image():
    png = _make_solid_png(200, 200, "#FF5500")
    palette = extract_palette(png, k=1)
    assert len(palette) == 1
    assert palette[0].startswith("#")


def test_extract_palette_returns_k_colors():
    img = _make_split_png("#FF0000", "#0000FF", size=200)
    palette = extract_palette(img, k=2)
    assert len(palette) == 2
    assert palette[0] != palette[1]


def test_autogenerated_brand_valid_contrast():
    png = _make_solid_png(200, 200, "#14213D")
    info = autogenerated_brand(png)
    assert info["is_valid"] is True
    assert info["level"] in ("AA", "AAA")
    assert len(info["palette"]) >= 2


def test_autogenerated_brand_pastel_logo():
    img = _make_split_png("#FFB3C1", "#FFFFFF", size=200)
    info = autogenerated_brand(img)
    assert info["is_valid"] is True
    assert info["level"] in ("AA", "AAA")


def test_autogenerated_brand_saturated_logo():
    img = _make_split_png("#FF3333", "#1A1A2E", size=200)
    info = autogenerated_brand(img)
    assert info["is_valid"] is True
