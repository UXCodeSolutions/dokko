@router.post("/tenants", response_model=TenantOut, status_code=status.HTTP_201_CREATED)
def create_tenant(
    body: CreateTenantRequest,
    user: dict = Depends(_require_super_admin),
):
    """
    Crea un nuevo tenant con su account_owner asociado al super-admin actual.
    Usa supabase_admin (service role) para bypasear RLS completamente.
    """
    user_id = user["sub"]
    user_email = user.get("email", "admin@dokko.com")

    # 1. Upsert del account_owner (service role bypasea RLS)
    existing_owner = supabase_admin.table("account_owners")\
        .select("id")\
        .eq("user_id", user_id)\
        .maybe_single()\
        .execute()

    if existing_owner is not None and existing_owner.data:
        owner_id = existing_owner.data["id"]
    else:
        new_owner = supabase_admin.table("account_owners").insert({
            "user_id": user_id,
            "email": user_email,
        }).execute()
        owner_id = new_owner.data[0]["id"]

    # 2. Crear el tenant
    brand_config = {
        "primary_color": body.primary_color,
        "secondary_color": body.secondary_color,
    }
    if body.logo_url:
        brand_config["logo_url"] = body.logo_url

    tenant_res = supabase_admin.table("tenants").insert({
        "name": body.name,
        "module_slug": body.module_slug,
        "owner_id": owner_id,
        "brand_config": brand_config,
    }).execute()

    tenant_id = tenant_res.data[0]["id"]

    # 3. Crear el usuario de Auth del tenant con su tenant_id en app_metadata
    try:
        new_user = supabase_admin.auth.admin.create_user({
            "email": body.admin_email,
            "password": body.admin_password,
            "email_confirm": True,
            "app_metadata": {"tenant_id": tenant_id},
        })
    except Exception as e:
        # Hacemos rollback manual del tenant creado (y sus dependencias en cascada si existen)
        supabase_admin.table("tenants").delete().eq("id", tenant_id).execute()
        error_msg = str(e)
        if "already been registered" in error_msg:
            raise HTTPException(status_code=400, detail="Este correo ya está registrado. Usa uno diferente para el administrador del tenant.")
        raise HTTPException(status_code=400, detail=f"Error creando usuario: {error_msg}")

    # 4. Vincular en tenant_users
    supabase_admin.table("tenant_users").insert({
        "tenant_id": tenant_id,
        "user_id": new_user.user.id,
        "role": "admin",
    }).execute()

    return tenant_res.data[0]


@router.get("/tenants")
def list_tenants(user: dict = Depends(_require_super_admin)):
    """Lista todos los tenants (solo super-admin)."""
    res = supabase_admin.table("tenants")\
        .select("*, account_owners(email)")\
        .order("created_at", desc=True)\
        .execute()
    return res.data


@router.get("/tenants/{tenant_id}")
def get_tenant(tenant_id: str, user: dict = Depends(_require_super_admin)):
    """Detalle de un tenant (solo super-admin)."""
    res = supabase_admin.table("tenants")\
        .select("*, account_owners(email), tenant_users(*)")\
        .eq("id", tenant_id)\
        .maybe_single()\
        .execute()
    if res is None or not res.data:
        raise HTTPException(status_code=404, detail="Tenant no encontrado.")
    return res.data


@router.patch("/tenants/{tenant_id}")
def update_tenant_details(
    tenant_id: str,
    body: dict,
    user: dict = Depends(_require_super_admin),
):
    """Actualiza datos básicos del tenant (nombre, días de retención)."""
    allowed_fields = {"name", "retention_days", "status"}
    payload = {k: v for k, v in body.items() if k in allowed_fields}
    if not payload:
        raise HTTPException(status_code=400, detail="Sin campos válidos para actualizar.")

    res = supabase_admin.table("tenants")\
        .update(payload)\
        .eq("id", tenant_id)\
        .execute()

    if not res.data:
        raise HTTPException(status_code=404, detail="Tenant no encontrado.")
    return res.data[0]


@router.patch("/tenants/{tenant_id}/status")
def update_tenant_status(
    tenant_id: str,
    body: dict,
    user: dict = Depends(_require_super_admin),
):
    """Activa / suspende / cancela un tenant."""
    new_status = body.get("status")
    if new_status not in ("active", "suspended", "cancelled"):
        raise HTTPException(status_code=400, detail="Estado inválido.")

    res = supabase_admin.table("tenants")\
        .update({"status": new_status})\
        .eq("id", tenant_id)\
        .execute()

    if not res.data:
        raise HTTPException(status_code=404, detail="Tenant no encontrado.")
    return res.data[0]


