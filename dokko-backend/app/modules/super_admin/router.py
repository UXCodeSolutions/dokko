from fastapi import APIRouter, Depends, HTTPException, status, File, UploadFile
from pydantic import BaseModel
from typing import Optional
from app.core.auth import get_current_user
from app.core.supabase_client import supabase_admin
from app.core.branding import (
    accessible_palette,
    autogenerated_brand,
    hex_to_rgb,
)


router = APIRouter()


def _require_super_admin(user: dict = Depends(get_current_user)) -> dict:
    """Dependencia que valida que el usuario autenticado es super-admin."""
    is_admin = user.get("app_metadata", {}).get("is_super_admin", False)
    if not is_admin:
        raise HTTPException(status_code=403, detail="Acceso restringido a super-admins.")
    return user


