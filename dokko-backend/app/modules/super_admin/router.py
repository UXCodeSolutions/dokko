class BrandValidateRequest(BaseModel):
    primary_color: str = "#3E63DD"
    secondary_color: str = "#111113"


class BrandUpdateRequest(BaseModel):
    primary_color: Optional[str] = None
    secondary_color: Optional[str] = None
    logo_url: Optional[str] = None


@router.post("/brand/validate")
def validate_brand(
    body: BrandValidateRequest,
    user: dict = Depends(_require_super_admin),
):
    """Valida contraste de una paleta y deriva colores de texto legibles."""
    try:
        info = accessible_palette(body.primary_color, body.secondary_color)
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    return info


@router.post("/brand/extract")
def extract_brand_from_logo(
    file: UploadFile = File(...),
    user: dict = Depends(_require_super_admin),
):
    """
    Extrae paleta dominante desde el logo (backend Python/Pillow) y devuelve
    colores validados con contraste AA. No modifica ningún tenant.
    """
    content = file.file.read()
    if not content:
        raise HTTPException(status_code=400, detail="Archivo vacío.")
    try:
        info = autogenerated_brand(content)
    except Exception as e:
        raise HTTPException(
            status_code=400,
            detail=f"No se pudo procesar la imagen. Usa un logo PNG/JPG/WebP: {e}",
        )
    return info


@router.patch("/tenants/{tenant_id}/brand")
def update_tenant_brand(
    tenant_id: str,
    body: BrandUpdateRequest,
    user: dict = Depends(_require_super_admin),
):
    """Actualiza brand_config de un tenant (colores validados + logo)."""
    current = supabase_admin.table("tenants")\
        .select("brand_config")\
        .eq("id", tenant_id)\
        .maybe_single()\
        .execute()
    if current is None or not current.data:
        raise HTTPException(status_code=404, detail="Tenant no encontrado.")

    brand = dict(current.data.get("brand_config") or {})
    if body.primary_color is not None:
        hex_to_rgb(body.primary_color)  # valida formato
        brand["primary_color"] = body.primary_color
    if body.secondary_color is not None:
        hex_to_rgb(body.secondary_color)  # valida formato
        brand["secondary_color"] = body.secondary_color
    if body.logo_url is not None:
        if body.logo_url.strip():
            brand["logo_url"] = body.logo_url.strip()
        else:
            brand.pop("logo_url", None)

    res = supabase_admin.table("tenants")\
        .update({"brand_config": brand})\
        .eq("id", tenant_id)\
        .execute()
    return res.data[0]
