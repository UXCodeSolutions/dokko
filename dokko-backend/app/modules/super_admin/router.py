class CreateTenantRequest(BaseModel):
    name: str
    module_slug: str
    primary_color: Optional[str] = "#3E63DD"
    secondary_color: Optional[str] = "#111113"
    logo_url: Optional[str] = None
    admin_email: str
    admin_password: str


class TenantOut(BaseModel):
    id: str
    name: str
    module_slug: str
    brand_config: dict
    status: str


