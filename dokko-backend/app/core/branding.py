"""
FASE 23 — Sistema de branding completo.

Extracción de color desde logo (backend Python) y validación de contraste
automática (WCAG 2.x AA / AAA) para garantizar que el texto sobre los colores
de marca siga siendo legible sin ajuste manual, con cualquier paleta.
"""
from __future__ import annotations

import io
from typing import List, Tuple


# ── Conversión HEX ↔ RGB ──────────────────────────────────────────────────────

def hex_to_rgb(hex_color: str) -> Tuple[int, int, int]:
    if not isinstance(hex_color, str):
        raise ValueError(f"Color hexadecimal inválido: {hex_color!r}")
    h = hex_color.strip().lstrip("#")
    if len(h) != 6 or not all(c in "0123456789abcdefABCDEF" for c in h):
        raise ValueError(f"Color hexadecimal inválido: {hex_color!r}")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def rgb_to_hex(rgb: Tuple[int, int, int]) -> str:
    return "#%02X%02X%02X" % (max(0, min(255, int(rgb[0]))),
                              max(0, min(255, int(rgb[1]))),
                              max(0, min(255, int(rgb[2]))))


# ── Contraste (WCAG 2.x) ──────────────────────────────────────────────────────

def _linearize(channel: float) -> float:
    c = channel / 255.0
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def relative_luminance(rgb: Tuple[int, int, int]) -> float:
    r, g, b = (_linearize(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(a: Tuple[int, int, int], b: Tuple[int, int, int]) -> float:
    la, lb = relative_luminance(a), relative_luminance(b)
    lighter, darker = max(la, lb), min(la, lb)
    return (lighter + 0.05) / (darker + 0.05)


def pick_text_color(bg_rgb: Tuple[int, int, int], threshold: float = 4.5) -> str:
    """
    Elige texto blanco o negro sobre `bg_rgb` buscando alcanzar `threshold`.
    Devuelve el hex del color con mejor contraste (nunca rompe).
    """
    candidates = [(255, 255, 255), (10, 10, 11), (0, 0, 0)]
    best = ("#FFFFFF", 0.0)
    for cand in candidates:
        ratio = contrast_ratio(bg_rgb, cand)
        if ratio >= threshold:
            return rgb_to_hex(cand), ratio
        if ratio > best[1]:
            best = (rgb_to_hex(cand), ratio)
    return best


def accessible_palette(primary: str, secondary: str = "#111113") -> dict:
    """Valida contraste y deriva on-primary / on-secondary legibles."""
    p_rgb = hex_to_rgb(primary)
    s_rgb = hex_to_rgb(secondary)
    on_primary, ratio_p = pick_text_color(p_rgb)
    on_secondary, ratio_s = pick_text_color(s_rgb, threshold=3.0)
    ratio = round(ratio_p, 2)
    level = "AAA" if ratio >= 7.0 else ("AA" if ratio >= 4.5 else "FALLA")
    return {
        "primary_color": rgb_to_hex(p_rgb),
        "secondary_color": rgb_to_hex(s_rgb),
        "on_primary": rgb_to_hex(hex_to_rgb(on_primary)),
        "on_secondary": rgb_to_hex(hex_to_rgb(on_secondary)),
        "primary_text_ratio": ratio,
        "secondary_text_ratio": round(ratio_s, 2),
        "level": level,
        "is_valid": ratio >= 4.5,
    }


# ── Extracción de paleta desde el logo ────────────────────────────────────────

def extract_palette(image_bytes: bytes, k: int = 3) -> List[str]:
    """
    Extrae los `k` colores dominantes de una imagen (PNG/JPG/WebP) usando
    cuantización de color de Pillow. Devuelve hexs ordenados por frecuencia.
    """
    try:
        from PIL import Image
    except ImportError as exc:  # pragma: no cover
        raise RuntimeError("Pillow no está instalado. Ejecuta: pip install Pillow") from exc

    img = Image.open(io.BytesIO(image_bytes)).convert("RGB")
    img.thumbnail((200, 200))
    small = img.resize((48, 48))
    if small.mode != "P":
        small = small.quantize(colors=k)
    palette = small.getpalette() or []
    counts = small.getcolors(maxcolors=48 * 48) or [(0, 0)]
    counts.sort(key=lambda item: item[0], reverse=True)

    colors: List[str] = []
    for _, idx in counts[:k]:
        base = idx * 3
        rgb = (palette[base], palette[base + 1], palette[base + 2])
        color = rgb_to_hex(rgb)
        if color not in colors:
            colors.append(color)
    while len(colors) < k:
        colors.append("#111113")
    return colors


def autogenerated_brand(image_bytes: bytes) -> dict:
    """Paleta completa derivada de un logo con validación de contraste."""
    palette = extract_palette(image_bytes)
    primary = palette[0]
    secondary = palette[1] if len(palette) > 1 else "#111113"
    info = accessible_palette(primary, secondary)
    info["palette"] = palette[:3]
    return info